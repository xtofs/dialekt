namespace SyntaxGenerator;

using System.Text;
using Dialekt.Green;

/// <summary>Generates the typed views over <see cref="SyntaxNode"/>s from <see cref="SyntaxSchema"/>.</summary>
public static class Generator
{
    public static string DefaultOutputPath()
    {
        var dir = new DirectoryInfo(Directory.GetCurrentDirectory());
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "tonto.slnx")))
        {
            dir = dir.Parent;
        }
        return Path.Combine(dir?.FullName ?? ".", "src", "dialekt", "Syntax", "Generated", "SyntaxViews.g.cs");
    }

    public static string Generate()
    {
        var kinds = Enum.GetValues<SyntaxKind>();
        var tokenOnly = Enum.GetValues<SyntaxCategory>()
            .Where(c => c != SyntaxCategory.None)
            .ToDictionary(c => c, c => kinds.Where(k => SyntaxSchema.IsInCategory(c, k)).All(SyntaxFacts.IsToken));

        var sb = new StringBuilder();
        sb.Append("""
            // <auto-generated>
            // Generated by tools/SyntaxGenerator from Dialekt.Green.SyntaxSchema. Do not edit; run
            //   dotnet run --project tools/SyntaxGenerator
            // </auto-generated>
            #nullable enable
            namespace Dialekt.Syntax;

            using Dialekt.Green;

            """.Replace("\r\n", "\n"));

        foreach (var kind in kinds)
        {
            var slots = SyntaxSchema.GetSlots(kind);
            if (slots.IsEmpty && kind != SyntaxKind.Error) continue;
            WriteNodeView(sb, kind, slots.ToArray(), tokenOnly);
        }

        foreach (var category in Enum.GetValues<SyntaxCategory>().Where(c => c != SyntaxCategory.None && !tokenOnly[c]))
        {
            WriteCategoryView(sb, category, kinds.Where(k => SyntaxSchema.IsInCategory(category, k)).ToList());
        }
        return sb.ToString();
    }

    private static string TypeOf(SlotSpec slot, Dictionary<SyntaxCategory, bool> tokenOnly)
    {
        if (slot.Category != SyntaxCategory.None)
        {
            return tokenOnly[slot.Category] ? "SyntaxToken" : slot.Category + "Syntax";
        }
        return SyntaxFacts.IsToken(slot.Kind) ? "SyntaxToken" : slot.Kind + "Syntax";
    }

    private static void WriteNodeView(StringBuilder sb, SyntaxKind kind, SlotSpec[] slots, Dictionary<SyntaxCategory, bool> tokenOnly)
    {
        var name = kind + "Syntax";
        var description = slots.Length == 0
            ? "no slots"
            : string.Join(", ", slots.Select(s => s.Name + s.Shape switch { SlotShape.Optional => "?", SlotShape.List => "*", SlotShape.SeparatedList => "*", _ => "" }));

        sb.AppendLine();
        sb.AppendLine($"/// <summary>A <see cref=\"SyntaxKind.{kind}\"/> node. Slots: {description}.</summary>");
        sb.AppendLine($"public readonly struct {name} : ISyntaxView<{name}>");
        sb.AppendLine("{");
        sb.AppendLine($"    public {name}(SyntaxNode node)");
        sb.AppendLine("    {");
        sb.AppendLine($"        SyntaxViews.AssertKind(node, SyntaxKind.{kind});");
        sb.AppendLine("        Node = node;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public SyntaxNode Node { get; }");
        sb.AppendLine($"    public static {name} Create(SyntaxNode node) => new(node);");
        sb.AppendLine();
        sb.AppendLine($"    public static bool TryCreate(SyntaxNode node, out {name} value)");
        sb.AppendLine("    {");
        sb.AppendLine($"        value = node.Kind == SyntaxKind.{kind} ? new(node) : default;");
        sb.AppendLine($"        return node.Kind == SyntaxKind.{kind};");
        sb.AppendLine("    }");

        for (var i = 0; i < slots.Length; i++)
        {
            var slot = slots[i];
            var type = TypeOf(slot, tokenOnly);
            sb.AppendLine();
            switch (slot.Shape)
            {
                case SlotShape.Required:
                    sb.AppendLine($"    public {type} {slot.Name} => SyntaxViews.Required<{type}>(Node, {i});");
                    break;
                case SlotShape.Optional:
                    sb.AppendLine($"    /// <summary>Null if the part is not there.</summary>");
                    sb.AppendLine($"    public {type}? {slot.Name} => SyntaxViews.Optional<{type}>(Node, {i});");
                    break;
                case SlotShape.List:
                    sb.AppendLine($"    public SyntaxList<{type}> {slot.Name} => new(Node.GetChild({i}));");
                    break;
                case SlotShape.SeparatedList:
                    sb.AppendLine($"    public SeparatedSyntaxList<{type}> {slot.Name} => new(Node.GetChild({i}));");
                    break;
            }
        }

        sb.AppendLine();
        sb.AppendLine($"    public static implicit operator SyntaxNode({name} value) => value.Node;");
        sb.AppendLine("}");
    }

    private static void WriteCategoryView(StringBuilder sb, SyntaxCategory category, List<SyntaxKind> members)
    {
        var name = category + "Syntax";
        sb.AppendLine();
        sb.AppendLine($"/// <summary>Any of: {string.Join(", ", members)}.</summary>");
        sb.AppendLine($"public readonly struct {name} : ISyntaxView<{name}>");
        sb.AppendLine("{");
        sb.AppendLine($"    public {name}(SyntaxNode node)");
        sb.AppendLine("    {");
        sb.AppendLine($"        SyntaxViews.AssertCategory(node, SyntaxCategory.{category});");
        sb.AppendLine("        Node = node;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public SyntaxNode Node { get; }");
        sb.AppendLine("    public SyntaxKind Kind => Node.Kind;");
        sb.AppendLine($"    public static {name} Create(SyntaxNode node) => new(node);");
        sb.AppendLine();
        sb.AppendLine($"    public static bool TryCreate(SyntaxNode node, out {name} value)");
        sb.AppendLine("    {");
        sb.AppendLine($"        var matches = SyntaxSchema.IsInCategory(SyntaxCategory.{category}, node.Kind);");
        sb.AppendLine("        value = matches ? new(node) : default;");
        sb.AppendLine("        return matches;");
        sb.AppendLine("    }");

        foreach (var member in members)
        {
            var type = member + "Syntax";
            sb.AppendLine();
            sb.AppendLine($"    /// <summary>This node as a <see cref=\"SyntaxKind.{member}\"/>, or null if it is something else.</summary>");
            sb.AppendLine($"    public {type}? As{member}() => Node.Kind == SyntaxKind.{member} ? new {type}(Node) : null;");
            sb.AppendLine($"    public static implicit operator {name}({type} value) => new(value.Node);");
        }

        sb.AppendLine();
        sb.AppendLine($"    public static implicit operator SyntaxNode({name} value) => value.Node;");
        sb.AppendLine("}");
    }
}
